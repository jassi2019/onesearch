export const TOPICS = TOPIC_GROUPS.flatMap((g) =>
  g.topics.map((t) => ({ ...t, group: g.group, emoji: g.emoji }))
);

export function getTopic(slug) {
  return TOPICS.find((t) => t.slug === slug) || null;
}

export function relatedTopics(slug, count = 6) {
  const topic = getTopic(slug);
  if (!topic) return [];
  const sameGroup = TOPICS.filter((t) => t.group === topic.group && t.slug !== slug);
  const others = TOPICS.filter((t) => t.group !== topic.group && t.slug !== slug);
  return [...sameGroup, ...others].slice(0, count);
}
